-- Ocorrências do evento (aba Ocorrências da cozinha), no padrão do Anne Gestão: tudo que
-- fugiu do planejado (atraso, falta de insumo, temperatura, carregamento, equipamento,
-- acidente, pedido do cliente). Fica no histórico do evento e sai junto quando o evento é
-- excluído. O tipo é validado só no DTO (Dominio.RE_TIPO_OCORRENCIA), sem CHECK.
CREATE TABLE evento_ocorrencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    tipo VARCHAR(30) NOT NULL,
    quem VARCHAR(80) NOT NULL,
    texto VARCHAR(2000) NOT NULL,
    acao VARCHAR(2000) NOT NULL DEFAULT '',
    quando TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolvida BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX ix_evento_ocorrencias_evento ON evento_ocorrencias (evento_id);
