-- Evento como projeto, no padrão do Anne Gestão: plano de logística, orçamento dos custos que
-- não saem das fichas técnicas e o retrato guardado ao fechar o evento. Uma linha por evento em
-- cada tabela, criada só quando a gestão salva (ou fecha); sem linha, a ficha mostra o plano vazio.
-- Saem junto quando o evento é excluído e ficam fora do backup, como evento_etapas e evento_equipe.

-- Logística e transporte: veículos, motorista e viagens em texto livre; horários de saída da
-- fábrica, início da montagem no local e retorno previsto.
CREATE TABLE evento_logistica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    veiculos VARCHAR(200) NOT NULL DEFAULT '',
    motorista VARCHAR(120) NOT NULL DEFAULT '',
    viagens VARCHAR(120) NOT NULL DEFAULT '',
    saida TIME,
    montagem TIME,
    retorno TIME,
    obs VARCHAR(2000) NOT NULL DEFAULT '',
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_por VARCHAR(100),
    CONSTRAINT uq_evento_logistica_evento UNIQUE (evento_id)
);

-- Orçamento do evento: custos previstos de transporte e de locação/outros. equipe só vale
-- enquanto não há escala montada (com escala, o previsto de equipe é o total das diárias) e
-- fica nula quando nunca foi informada.
CREATE TABLE evento_orcamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    equipe NUMERIC(15, 2),
    transporte NUMERIC(15, 2) NOT NULL DEFAULT 0,
    outros NUMERIC(15, 2) NOT NULL DEFAULT 0,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_por VARCHAR(100),
    CONSTRAINT uq_evento_orcamento_evento UNIQUE (evento_id)
);

-- Retrato do fechamento: o resultado do evento no momento em que passou para Acertado.
-- Lançamentos posteriores não mudam o retrato; fechar de novo (depois de reabrir) o substitui.
-- por_tipo: {"previsto": {ab, equipe, transporte, outros}, "realizado": {...}};
-- pendencias: etapas ainda sem marcar quando o evento foi fechado.
CREATE TABLE evento_fechamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    fechado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    fechado_por VARCHAR(100) NOT NULL DEFAULT '',
    receita NUMERIC(15, 2) NOT NULL DEFAULT 0,
    recebido NUMERIC(15, 2) NOT NULL DEFAULT 0,
    custo_previsto NUMERIC(15, 2) NOT NULL DEFAULT 0,
    custo_realizado NUMERIC(15, 2) NOT NULL DEFAULT 0,
    resultado NUMERIC(15, 2) NOT NULL DEFAULT 0,
    cmv NUMERIC(9, 3),
    por_tipo JSONB NOT NULL DEFAULT '{}',
    pendencias JSONB NOT NULL DEFAULT '[]',
    CONSTRAINT uq_evento_fechamento_evento UNIQUE (evento_id)
);
