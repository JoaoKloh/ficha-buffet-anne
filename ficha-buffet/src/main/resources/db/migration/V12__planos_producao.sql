-- Planos de produção do Restaurante ANNE e da Chocolates Marie & Anne (tela Produção), no
-- padrão do Anne Gestão: separados dos eventos do buffet. A tabela não se chama "producoes"
-- porque "producao" já é a tabela dos eventos. Lista de produção, insumos e compras são
-- calculados na leitura; grava-se o plano, os itens e a previsão da carta.
--   unidade: restaurante | chocolates; status: planejado | em_producao | concluido
--   (validados só no DTO, sem CHECK);
--   previsao: pratos da carta previstos no período ("Calcular pela carta"), pratoVendaId -> quantidade.
CREATE TABLE planos_producao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(160) NOT NULL,
    unidade VARCHAR(12) NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'planejado',
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    obs VARCHAR(2000) NOT NULL DEFAULT '',
    previsao JSONB NOT NULL DEFAULT '{}',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_planos_producao_unidade ON planos_producao (unidade);

-- Item do plano: a ficha e a quantidade na unidade de rendimento dela. Concluir o item cria um
-- lote em Estoque › Pré-preparos (é o lote que baixa os insumos, uma vez só); o lote fica
-- ligado ao item até o item ser desfeito.
CREATE TABLE planos_producao_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id BIGINT NOT NULL REFERENCES planos_producao (id),
    preparacao_id BIGINT NOT NULL REFERENCES pratos (id),
    qtd DOUBLE PRECISION NOT NULL,
    feito BOOLEAN NOT NULL DEFAULT FALSE,
    feito_em DATE,
    lote_preparo_id BIGINT REFERENCES lotes_preparo (id),
    CONSTRAINT uq_planos_producao_itens_lote UNIQUE (lote_preparo_id)
);

CREATE INDEX ix_planos_producao_itens_plano ON planos_producao_itens (plano_id);
CREATE INDEX ix_planos_producao_itens_preparacao ON planos_producao_itens (preparacao_id);

-- Unidade de negócio do lote, gravada ao concluir um item de plano (restaurante | chocolates).
-- Nula nos demais lotes, que contam como restaurante no KPI "Pré-preparos prontos".
ALTER TABLE lotes_preparo
    ADD COLUMN unidade_negocio VARCHAR(12);
