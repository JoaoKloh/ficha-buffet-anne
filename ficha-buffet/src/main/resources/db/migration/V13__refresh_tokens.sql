-- Refresh tokens das sessões de login (renovação do access token de 20 min sem pedir a senha).
-- Cada login abre uma sessão (sessao_id) por navegador; a cada renovação o token usado é
-- revogado (ROTACIONADO) e um novo é gravado na mesma sessão. Sessões de outros dispositivos
-- do mesmo usuário são independentes.
--   token_hash: SHA-256 (hex) do token; o valor bruto só existe no cookie do navegador.
--   motivo_revogacao: ROTACIONADO | LOGOUT | REUTILIZADO | NOVO_LOGIN (validado só no Java, sem CHECK).
--   Reapresentar um token já rotacionado revoga a sessão inteira (REUTILIZADO).
CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario (usuario_id) ON DELETE CASCADE,
    sessao_id UUID NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_em TIMESTAMPTZ NOT NULL,
    revogado_em TIMESTAMPTZ,
    motivo_revogacao VARCHAR(20),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_expira CHECK (expira_em > criado_em),
    CONSTRAINT ck_refresh_tokens_revogacao CHECK ((revogado_em IS NULL) = (motivo_revogacao IS NULL))
);

CREATE INDEX ix_refresh_tokens_usuario ON refresh_tokens (usuario_id);
CREATE INDEX ix_refresh_tokens_sessao ON refresh_tokens (sessao_id);

-- No máximo um token ativo por sessão: duas rotações concorrentes do mesmo token nunca deixam
-- dois tokens válidos na mesma sessão.
CREATE UNIQUE INDEX uq_refresh_tokens_sessao_ativo ON refresh_tokens (sessao_id) WHERE revogado_em IS NULL;
