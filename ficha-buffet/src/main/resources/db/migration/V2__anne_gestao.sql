-- 4. ingredientes (itens de estoque)
-- ---------------------------------------------------------------------------
ALTER TABLE ingredientes
    ADD COLUMN tipo VARCHAR(20) NOT NULL DEFAULT 'ingrediente',
    ADD COLUMN local VARCHAR(40) NOT NULL DEFAULT 'Depósito',
    ADD COLUMN unidade_compra VARCHAR(60) NOT NULL DEFAULT '',
    ADD COLUMN fator_compra DOUBLE PRECISION,
    ADD COLUMN estoque_minimo DOUBLE PRECISION NOT NULL DEFAULT 0,
    ADD COLUMN atualizado_em DATE NOT NULL DEFAULT CURRENT_DATE;

-- Custo por unidade com 4 casas; o custo por grama vira custo por quilo.
ALTER TABLE ingredientes ALTER COLUMN custo_por_unidade TYPE NUMERIC(15,4)
    USING round(custo_por_unidade::numeric * CASE WHEN unidade IN ('g', 'gramas', 'ml') THEN 1000 ELSE 1 END, 4);
UPDATE ingredientes SET custo_por_unidade = 0 WHERE custo_por_unidade IS NULL;
ALTER TABLE ingredientes ALTER COLUMN custo_por_unidade SET DEFAULT 0;
ALTER TABLE ingredientes ALTER COLUMN custo_por_unidade SET NOT NULL;

UPDATE ingredientes SET unidade = CASE
    WHEN unidade IN ('g', 'gramas', 'kg') THEN 'kg'
    WHEN unidade IN ('ml', 'l', 'L') THEN 'l'
    WHEN unidade IN ('un', 'dz', 'maço', 'garrafa', 'botijão') THEN unidade
    ELSE 'un' END;
ALTER TABLE ingredientes ALTER COLUMN unidade TYPE VARCHAR(10);
ALTER TABLE ingredientes ALTER COLUMN unidade SET DEFAULT 'kg';
ALTER TABLE ingredientes ALTER COLUMN unidade SET NOT NULL;

