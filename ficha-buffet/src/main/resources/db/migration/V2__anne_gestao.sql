CREATE TABLE cozinha_execucoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id) ON DELETE CASCADE,
    kind VARCHAR(12) NOT NULL,
    item_cardapio_id BIGINT REFERENCES producao_prato (id) ON DELETE CASCADE,
    ingrediente_id BIGINT REFERENCES ingredientes (id),
    referencia VARCHAR(60),
    produzido DOUBLE PRECISION,
    produzido_em DATE,
    executado_por VARCHAR(100) NOT NULL DEFAULT '',
    enviado_q DOUBLE PRECISION,
    enviado BOOLEAN NOT NULL DEFAULT FALSE,
    enviado_em TIMESTAMPTZ,
    separado_por VARCHAR(100) NOT NULL DEFAULT '',
    retorno DOUBLE PRECISION,
    conferido_por VARCHAR(100) NOT NULL DEFAULT '',
    obs VARCHAR(300) NOT NULL DEFAULT '',
    temp_saida DOUBLE PRECISION,
    temp_chegada DOUBLE PRECISION,
    saiu DOUBLE PRECISION,
    voltou DOUBLE PRECISION,
    avaria DOUBLE PRECISION,
    feito BOOLEAN NOT NULL DEFAULT FALSE,
    resp VARCHAR(100) NOT NULL DEFAULT '',
    dn_set BOOLEAN NOT NULL DEFAULT FALSE,
    dn INTEGER,
    itens_comprados JSONB NOT NULL DEFAULT '{}',
    chef_por VARCHAR(100) NOT NULL DEFAULT '',
    chef_hora TIME,
    carga_por VARCHAR(100) NOT NULL DEFAULT '',
    carga_hora TIME,
    receb_por VARCHAR(100) NOT NULL DEFAULT '',
    receb_hora TIME,
    retorno_por VARCHAR(100) NOT NULL DEFAULT '',
    retorno_hora TIME,
    veiculo VARCHAR(100) NOT NULL DEFAULT '',
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Um registro por evento + tipo + referência (item do cardápio, insumo ou chave da linha).
    CONSTRAINT uk_cozinha_execucoes_chave UNIQUE NULLS NOT DISTINCT (evento_id, kind, item_cardapio_id, ingrediente_id, referencia)
);
CREATE INDEX ix_cozinha_execucoes_item_cardapio ON cozinha_execucoes (item_cardapio_id);
CREATE INDEX ix_cozinha_execucoes_ingrediente ON cozinha_execucoes (ingrediente_id);

