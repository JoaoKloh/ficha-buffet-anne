    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(12) NOT NULL,
    preparacao_id BIGINT NOT NULL REFERENCES pratos (id),
    qtd DOUBLE PRECISION NOT NULL,
    saldo DOUBLE PRECISION NOT NULL,
    unidade VARCHAR(10) NOT NULL,
    produzido_em DATE NOT NULL,
    validade DATE,
    destino VARCHAR(15) NOT NULL DEFAULT 'restaurante',
    evento_id BIGINT REFERENCES producao (id),
    responsavel VARCHAR(100) NOT NULL DEFAULT '',
    obs VARCHAR(1000) NOT NULL DEFAULT '',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_lotes_preparo_codigo UNIQUE (codigo),
    CONSTRAINT ck_lotes_preparo_evento CHECK (destino <> 'evento' OR evento_id IS NOT NULL)
);
CREATE INDEX ix_lotes_preparo_preparacao ON lotes_preparo (preparacao_id);
CREATE INDEX ix_lotes_preparo_evento ON lotes_preparo (evento_id);
CREATE INDEX ix_lotes_preparo_com_saldo ON lotes_preparo (validade) WHERE saldo > 0;

CREATE TABLE lote_movimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_preparo_id BIGINT NOT NULL REFERENCES lotes_preparo (id) ON DELETE CASCADE,
    tipo VARCHAR(10) NOT NULL,
    data DATE NOT NULL,
    qtd DOUBLE PRECISION NOT NULL,
    para VARCHAR(15) NOT NULL,
    obs VARCHAR(300) NOT NULL DEFAULT '',
    em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_lote_movimento_lote ON lote_movimento (lote_preparo_id);

