ALTER TABLE clientes ADD COLUMN migracao_producao_id BIGINT;
INSERT INTO clientes (nome, migracao_producao_id) SELECT left(nome, 200), id FROM producao;
UPDATE producao p SET cliente_id = c.id, status = 'contratado'
  FROM clientes c WHERE c.migracao_producao_id = p.id;
ALTER TABLE clientes DROP COLUMN migracao_producao_id;

-- Código "AA-NNN": ano do evento e sequência dentro do ano.
UPDATE producao p SET codigo = c.codigo
  FROM (
    SELECT id,
           to_char(coalesce(data_evento, CURRENT_DATE), 'YY') || '-' ||
           lpad((row_number() OVER (PARTITION BY to_char(coalesce(data_evento, CURRENT_DATE), 'YY') ORDER BY id))::text, 3, '0') AS codigo
      FROM producao
  ) c
 WHERE c.id = p.id;

