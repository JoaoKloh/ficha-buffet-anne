-- 3. Unidades: tudo em kg e l
-- ---------------------------------------------------------------------------
-- As quantidades das fichas seguem a unidade do ingrediente: convertidas antes
-- de a unidade do ingrediente mudar.
UPDATE prato_ingrediente pi
   SET quantidade = pi.quantidade / 1000
  FROM ingredientes i
 WHERE i.id = pi.ingrediente_id AND i.unidade IN ('g', 'gramas', 'ml');

