-- Unidades de negócio (Buffet, Restaurante, Chocolates e Estrutura compartilhada),
-- pagamentos em partes, transferências entre unidades e auditoria dos lançamentos.

-- ---------------------------------------------------------------------------
-- 1. Lançamentos
-- ---------------------------------------------------------------------------
-- "transferencia" (tipo e origem) e "banco_restaurante" (conta) não cabiam nas colunas.
ALTER TABLE lancamentos_financeiros ALTER COLUMN tipo TYPE VARCHAR(15);
ALTER TABLE lancamentos_financeiros ALTER COLUMN origem TYPE VARCHAR(15);
ALTER TABLE lancamentos_financeiros ALTER COLUMN conta TYPE VARCHAR(20);

-- unidade nula = ainda sem unidade: o sistema deduz Buffet para lançamentos de
-- evento e Restaurante para a conta do restaurante; os demais ficam para classificar.
ALTER TABLE lancamentos_financeiros
    ADD COLUMN unidade VARCHAR(15),
    ADD COLUMN unidade_origem VARCHAR(15),
    ADD COLUMN unidade_destino VARCHAR(15),
    ADD COLUMN insumo_id BIGINT REFERENCES ingredientes (id),
    ADD COLUMN item VARCHAR(200),
    ADD COLUMN qtd DOUBLE PRECISION,
    ADD COLUMN unid VARCHAR(20),
    ADD COLUMN responsavel VARCHAR(100),
    ADD COLUMN obs VARCHAR(500),
    ADD COLUMN criado_por VARCHAR(100),
    ADD COLUMN alterado_por VARCHAR(100),
    ADD COLUMN alterado_em TIMESTAMPTZ;
CREATE INDEX ix_lancamentos_unidade ON lancamentos_financeiros (unidade);
CREATE INDEX ix_lancamentos_insumo ON lancamentos_financeiros (insumo_id);

-- ---------------------------------------------------------------------------
-- 2. Pagamentos e recebimentos (um lançamento pode ser pago em partes)
-- ---------------------------------------------------------------------------
CREATE TABLE lancamento_pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lancamento_id BIGINT NOT NULL REFERENCES lancamentos_financeiros (id) ON DELETE CASCADE,
    data DATE NOT NULL,
    valor NUMERIC(15,2) NOT NULL,
    conta VARCHAR(20) NOT NULL DEFAULT 'banco',
    forma VARCHAR(15) NOT NULL DEFAULT '',
    registrado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    registrado_por VARCHAR(100) NOT NULL DEFAULT ''
);
CREATE INDEX ix_lancamento_pagamentos_lancamento ON lancamento_pagamentos (lancamento_id);
CREATE INDEX ix_lancamento_pagamentos_data ON lancamento_pagamentos (data);

-- Cada lançamento já pago ou recebido vira um pagamento único, na data do pagamento.
INSERT INTO lancamento_pagamentos (lancamento_id, data, valor, conta, forma, registrado_em, registrado_por)
SELECT l.id, COALESCE(l.data_pagamento, l.data_competencia), l.valor, l.conta, COALESCE(l.forma_pag, ''), l.criado_em, 'migração'
  FROM lancamentos_financeiros l
 WHERE l.status = 'realizado';

-- ---------------------------------------------------------------------------
-- 3. Notas fiscais: unidade que paga e usa a compra
-- ---------------------------------------------------------------------------
ALTER TABLE notas_fiscais ADD COLUMN unidade VARCHAR(15);
