-- Etapas do evento marcadas à mão na ficha do evento (feito) e degustação dispensada.
-- As etapas detectadas pelo sistema (contrato, cardápio fechado, assinaturas da cozinha...)
-- são calculadas na leitura e não são gravadas. Uma linha por evento e etapa; a linha sai
-- quando a etapa volta a não estar feita nem dispensada.
CREATE TABLE evento_etapas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    etapa VARCHAR(20) NOT NULL,
    feito BOOLEAN NOT NULL DEFAULT FALSE,
    dispensada BOOLEAN NOT NULL DEFAULT FALSE,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_por VARCHAR(100),
    CONSTRAINT uq_evento_etapas_evento_etapa UNIQUE (evento_id, etapa)
);
