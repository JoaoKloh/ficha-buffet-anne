-- Equipe do buffet: cadastro das pessoas que trabalham nos eventos, reaproveitado de um
-- evento para o outro. Nome, telefone e Pix são da pessoa; função, horários e diária são
-- de cada escala (evento_equipe), porque mudam de evento para evento.
CREATE TABLE equipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    contato VARCHAR(40) NOT NULL DEFAULT '',
    pix VARCHAR(120) NOT NULL DEFAULT '',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    criado_por VARCHAR(100)
);

-- Escala do evento: uma linha por pessoa escalada. lancamento_id é a conta a pagar da
-- diária, depois de lançada; se o lançamento for excluído no Caixa, a diária volta a
-- ficar "fora do caixa".
CREATE TABLE evento_equipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    equipe_id BIGINT NOT NULL REFERENCES equipe (id),
    funcao VARCHAR(30) NOT NULL,
    chegada TIME,
    saida TIME,
    valor NUMERIC(15, 2) NOT NULL DEFAULT 0,
    lancamento_id BIGINT REFERENCES lancamentos_financeiros (id) ON DELETE SET NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    criado_por VARCHAR(100),
    CONSTRAINT uq_evento_equipe_evento_pessoa UNIQUE (evento_id, equipe_id)
);

CREATE INDEX ix_evento_equipe_equipe ON evento_equipe (equipe_id);
CREATE INDEX ix_evento_equipe_lancamento ON evento_equipe (lancamento_id);
