-- Ordens de produção da cozinha (aba Ordens e Painel do líder), no padrão do Anne Gestão:
-- as ordens não são gravadas; elas são geradas na leitura a partir do cardápio confirmado
-- e das fichas técnicas. Grava-se só o que a gestão e a equipe decidem: o mapa do evento
-- (ficha mestre), o plano de cada ordem, a execução da equipe, a liberação para expedição
-- e os setores da cozinha.

-- Campos de produção da ficha técnica, usados para gerar as ordens.
--   setor: setor de produção ('' = automático pela praça e categoria);
--   dn_producao: antecedência em dias antes do evento (nulo = padrão da praça);
--   tempo_min: tempo de uma receita, em minutos (nulo = não informado; a carga usa 30);
--   comprado_pronto: o fornecedor entrega pronto, a produção só retira do estoque.
ALTER TABLE pratos
    ADD COLUMN setor VARCHAR(40) NOT NULL DEFAULT '',
    ADD COLUMN dn_producao INTEGER,
    ADD COLUMN tempo_min INTEGER,
    ADD COLUMN equipamentos VARCHAR(200) NOT NULL DEFAULT '',
    ADD COLUMN armazenamento VARCHAR(300) NOT NULL DEFAULT '',
    ADD COLUMN comprado_pronto BOOLEAN NOT NULL DEFAULT FALSE;

-- Setores da cozinha. Renomeáveis e desativáveis, nunca excluídos: as ordens e as
-- fichas guardam o id do setor.
CREATE TABLE setores_producao (
    id VARCHAR(40) PRIMARY KEY,
    nome VARCHAR(60) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    ordem INTEGER NOT NULL DEFAULT 0
);

