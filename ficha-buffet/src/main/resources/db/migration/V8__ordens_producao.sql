-- Mapa de produção do evento (ficha mestre). A linha existe a partir de "Gerar mapa";
-- liberado_em nulo = só a gestão vê as ordens (em teste).
CREATE TABLE evento_producao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    gerado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    gerado_por VARCHAR(100),
    liberado_em TIMESTAMPTZ,
    responsavel VARCHAR(120) NOT NULL DEFAULT '',
    horarios VARCHAR(300) NOT NULL DEFAULT '',
    CONSTRAINT uq_evento_producao_evento UNIQUE (evento_id)
);

-- Plano da gestão para uma ordem: prazo (dias antes do evento), horário limite, setor e
-- responsável. Só existe para a ordem ajustada; sem linha, valem os padrões da ficha.
-- chave: m_<item do cardápio> (principal), f_<item> (finalização), s_<ficha> (sub-receita)
-- ou x_exp (expedição).
CREATE TABLE evento_ordem_plano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    chave VARCHAR(40) NOT NULL,
    dn INTEGER NOT NULL,
    hora TIME,
    setor VARCHAR(40) NOT NULL REFERENCES setores_producao (id),
    responsavel VARCHAR(80) NOT NULL DEFAULT '',
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_por VARCHAR(100),
    CONSTRAINT uq_evento_ordem_plano_evento_chave UNIQUE (evento_id, chave)
);

-- O que a equipe registrou na ordem. Sem linha, a ordem está pendente.
-- status: pendente, em_producao, em_conferencia, concluida ou bloqueada;
-- status_anterior: para onde a ordem volta ao ser desbloqueada;
-- historico: [{em, quem, acao}], as 40 últimas ações.
-- A baixa dos insumos no estoque é calculada a partir das ordens concluídas (conferidas).
CREATE TABLE evento_ordem_execucao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    chave VARCHAR(40) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pendente',
    status_anterior VARCHAR(16),
    responsavel VARCHAR(80) NOT NULL DEFAULT '',
    iniciado_por VARCHAR(80) NOT NULL DEFAULT '',
    iniciado_em TIMESTAMPTZ,
    concluido_por VARCHAR(80) NOT NULL DEFAULT '',
    concluido_em TIMESTAMPTZ,
    qtd DOUBLE PRECISION,
    perda DOUBLE PRECISION NOT NULL DEFAULT 0,
    obs VARCHAR(2000) NOT NULL DEFAULT '',
    conferido_por VARCHAR(80) NOT NULL DEFAULT '',
    conferido_em TIMESTAMPTZ,
    lote VARCHAR(40) NOT NULL DEFAULT '',
    motivo VARCHAR(40) NOT NULL DEFAULT '',
    motivo_txt VARCHAR(500) NOT NULL DEFAULT '',
    historico JSONB NOT NULL DEFAULT '[]',
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_evento_ordem_execucao_evento_chave UNIQUE (evento_id, chave)
);

-- Liberação do evento para expedição: conferências, horário de saída e quem autorizou.
-- conferencias: {preparacoes, quantidades, embalagens, temperaturas, utensilios,
-- equipamentos, bandejas, bebidas, veiculo} -> true/false.
CREATE TABLE evento_liberacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES producao (id),
    conferencias JSONB NOT NULL DEFAULT '{}',
    hora_saida TIME,
    autorizado_por VARCHAR(80) NOT NULL DEFAULT '',
    autorizado_em TIMESTAMPTZ,
    com_pendencias BOOLEAN NOT NULL DEFAULT FALSE,
    pendencias VARCHAR(2000) NOT NULL DEFAULT '',
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_evento_liberacao_evento UNIQUE (evento_id)
);
